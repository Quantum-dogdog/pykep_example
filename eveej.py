# -*- coding: utf-8 -*-
"""
EVEEJ (Earth - Venus - Earth - Earth - Jupiter) 多重力辅助转移轨道优化
=====================================================================
- 发射窗口: 1989-10-13 ~ 1989-10-23 (Galileo 任务真实发射窗口)
- 序列:     地球 -> 金星 -> 地球 -> 地球 -> 木星 (两次地球借力)
- 方法:     pykep 的 mga_1dsm (多重力辅助 + 每段一次深空机动)
- 求解器:   pygmo 群岛 (10 岛并行) + 自适应差分进化 (sade)

环境依赖: pip install pykep pygmo matplotlib
          (建议用 conda: conda install -c conda-forge pykep pygmo)
"""

import pygmo as pg
import pykep as pk
from pykep import epoch
from pykep.planet import jpl_lp          # JPL 低精度星历模型 (精度足够轨迹初设计)
from pykep.trajopt import mga_1dsm


def run():
    # ==================================================================
    # 1. 定义行星序列: Earth -> Venus -> Earth -> Earth -> Jupiter
    # ==================================================================
    seq = [
        jpl_lp('earth'),      # 出发行星
        jpl_lp('venus'),      # 第 1 次借力
        jpl_lp('earth'),      # 第 2 次借力
        jpl_lp('earth'),      # 第 3 次借力
        jpl_lp('jupiter'),    # 目标
    ]

    # ==================================================================
    # 2. 定义 UDP (User Defined Problem)
    #    注意: 所有参数在构造函数中一次传入, 不要事后修改属性!
    # ==================================================================
    udp = mga_1dsm(
        seq=seq,

        # ------------------------------------------------------------
        # 发射窗口
        # pykep 默认历元为 MJD2000 (2000-01-01 12:00 起算的天数)
        # 2000 年之前的日期用负数表示:
        #   -3729.5 -> 1989-10-13,  -3719.5 -> 1989-10-23
        # 也可用字符串写法 (二选一):
        #   t0=[epoch("1989-10-13"), epoch("1989-10-23")]
        # ------------------------------------------------------------
        t0=[epoch(-3729.5), epoch(-3719.5)],

        # ------------------------------------------------------------
        # 每一段的飞行时间窗口 [min, max], 单位: 天
        # 最后一段 E->J 放宽到 2~4 年: 借力后飞得越慢,
        # 到达木星的 v_inf 越小, 总 ΔV 越省 (约 6 年可达, Galileo 也飞了 6 年)
        # ------------------------------------------------------------
        tof=[
            [0.2 * 365.25, 1.0 * 365.25],   # Earth -> Venus : ~73~366 天
            [0.7 * 365.25, 1.3 * 365.25],   # Venus -> Earth : ~256~475 天
            [0.9 * 365.25, 1.5 * 365.25],   # Earth -> Earth : ~329~548 天
            [2.0 * 365.25, 4.0 * 365.25],   # Earth -> Jupiter: ~730~1461 天
        ],

        # ------------------------------------------------------------
        # v_inf 约束 [min, max], 单位: km/s
        # 同时约束出发端 C3 和到达端 v_inf (mga_1dsm 不支持分端设置)
        # ------------------------------------------------------------
        vinf=[0.1, 5.0],

        # 出发端超速损失计入目标函数 (从地球停车轨道出发时设 True)
        add_vinf_dep=True,

        # 到达端超速损失计入目标函数 (到达木星要被捕获)
        add_vinf_arr=True,

        # 单目标优化 (最小化总 ΔV); 设 True 则为 ΔV+飞行时间双目标
        multi_objective=False,
    )

    # 包装为 pygmo 问题, 并打印问题信息供核对 (维度应为 18)
    prob = pg.problem(udp)
    print(prob)

    # ==================================================================
    # 3. 算法: 群岛并行 + 自适应差分进化 (sade)
    #    MGA-1DSM 问题多局部极值、无梯度, 必须用全局算法;
    #    单个体 + COBYLA 之类的局部算法基本找不到好解
    # ==================================================================
    uda = pg.sade(gen=100)      # 每岛进化 100 代 (18 维问题, 500 代偏少)
    archi = pg.archipelago(
        n=10,                    # 10 个岛 (利用多核并行迁移)
        algo=uda,
        prob=prob,
        pop_size=20,             # 每岛 20 个个体
        seed=42,                 # 固定随机种子, 结果可复现; 想多试几次可改
    )

    print('Running a Self-Adaptive Differential Evolution Algorithm '
          '.... on 10 parallel islands')

    # ==================================================================
    # 4. 并行进化并等待所有岛完成
    #    注意: evolve() 不接受参数, 岛的数量在构造 archipelago 时给定
    # ==================================================================
    archi.evolve()
    archi.wait()

    # ==================================================================
    # 5. 提取结果
    #    champions_f = 各岛最优目标函数值 = 总 ΔV, 单位 m/s
    # ==================================================================
    fs = archi.get_champions_f()
    xs = archi.get_champions_x()
    idx = fs.index(min(fs))                 # 找 ΔV 最小的那个岛

    print('\n各岛 ΔV (m/s):', [round(f[0], 1) for f in fs])
    print('Best ΔV = %.1f m/s (= %.3f km/s)' % (min(fs)[0], min(fs)[0] / 1000))
    print('Chromo  :', xs[idx])

    # ==================================================================
    # 6. 解码并详细打印最优解
    #    本版本 pykep 的 mga_1dsm 染色体为 direct 编码, 18 维:
    #      x[0]        : t0 发射历元 (MJD2000, 直接可传给 epoch())
    #      x[1], x[2]  : 发射 v_inf 方向角 (u, v)
    #      x[3]        : 发射 v_inf 大小, 单位 m/s !
    #      第 1 段      : x[4]=eta1(DSM时刻比例), x[5]=T1(飞行时间/天)
    #      之后每段 4 维: [beta(近心点角), rp/rV, eta(DSM比例), T(飞行时间/天)]
    #                    即 x[6..9], x[10..13], x[14..17]
    #    时间累积: T_i 位于 x[5+4i] (i=0,1,2,3)
    # ==================================================================
    best = xs[idx]
    print('\n========== 最优解详情 ==========')

    # pykep 自带人可读解码, 会打印每段的历元/位置/速度/ΔV
    udp.pretty(best)

    # 自己再汇总一遍关键信息
    T = best[5::4]                          # 各段飞行时间 (天)
    print('\n发射 V_inf      : %.2f km/s' % (best[3] / 1000))   # 注意是 m/s, 除 1000
    print('发射历元        :', epoch(best[0]))                  # 直接是 MJD2000

    t_acc = best[0]
    for i, pl in enumerate(seq[1:]):        # seq[1:] = 到达的 4 个天体
        t_acc += T[i]
        print('到达 %-8s   : %s  (该段 %6.1f 天 ≈ %.2f 年)' % (
            pl.name, epoch(t_acc), T[i], T[i] / 365.25))

    print('总飞行时间      : %.1f 天 ≈ %.2f 年' % (sum(T), sum(T) / 365.25))

    # ==================================================================
    # 7. 绘制最优轨迹 (日心黄道面投影 + 各行星轨道)
    # ==================================================================
    try:
        import matplotlib
        matplotlib.use('TkAgg')             # 无显示环境(服务器)可改为 'Agg'
        import matplotlib.pyplot as plt
        udp.plot(best)                      # pykep 自带绘图
        plt.title('EVEEJ trajectory - total DV = %.2f km/s'
                  % (min(fs)[0] / 1000))
        plt.show()
    except Exception as e:
        print('绘图失败 (可忽略):', e)


if __name__ == '__main__':
    run()
