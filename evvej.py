# -*- coding: utf-8 -*-
"""
EVVEJ / VEEGA (Earth - Venus - Venus - Earth - Jupiter) 多重力辅助转移轨道优化
=============================================================================
- 序列:     地球 -> 金星 -> 金星 -> 地球 -> 木星 (两次金星借力 + 一次地球借力)
            这是 Galileo 任务 1989-10-18 发射时的真实路线 (VEEGA)
- 方法:     pykep 的 mga_1dsm (多重力辅助 + 每段一次深空机动)
- 求解器:   pygmo 群岛 (20 岛并行) + 自适应差分进化 (sade)

环境依赖: pip install pykep pygmo matplotlib
          (建议 conda: conda install -c conda-forge pykep pygmo)
"""

import pygmo as pg
from pykep import epoch
from pykep.planet import jpl_lp          # JPL 低精度星历 (轨迹初设计够用)
from pykep.trajopt import mga_1dsm


def run():
    # ==================================================================
    # 1. 行星序列: Earth -> Venus -> Venus -> Earth -> Jupiter
    #    (4 段转移, 3 次行星借力)
    # ==================================================================
    seq = [
        jpl_lp('earth'),      # 出发
        jpl_lp('venus'),      # 第 1 次借力 (金)
        jpl_lp('venus'),      # 第 2 次借力 (金)  ← VEEGA 的核心
        jpl_lp('earth'),      # 第 3 次借力 (地)  ← GA: Gravity Assist
        jpl_lp('jupiter'),    # 目标
    ]

    # ==================================================================
    # 2. 定义 UDP
    # ==================================================================
    udp = mga_1dsm(
        seq=seq,

        # ------------------------------------------------------------
        # 发射窗口: 1989-09-28 ~ 1989-11-12 (±30 天, 覆盖 Galileo
        # 真实发射日 1989-10-18, 即 MJD2000 = -3724.5)
        # pykep 默认历元 MJD2000, 2000 年前用负数
        # ------------------------------------------------------------
        t0=[epoch(-3744.5), epoch(-3689.5)],

        # ------------------------------------------------------------
        # 每一段飞行时间窗口 [min, max], 单位: 天
        # VEEGA 的关键: 两次金星借力之间是共振轨道 (~0.4~0.8 年),
        # 最后 E->J 放宽到 2~5 年, 慢飞省 ΔV
        # ------------------------------------------------------------
        tof=[
            [0.2 * 365.25, 1.0 * 365.25],   # E -> V  : 73~366 天
            [0.3 * 365.25, 0.9 * 365.25],   # V -> V  : 110~329 天 (金星共振段)
            [0.7 * 365.25, 1.3 * 365.25],   # V -> E  : 256~475 天
            [2.0 * 365.25, 5.0 * 365.25],   # E -> J  : 730~1826 天
        ],

        # 出发 C3 / 到达 v_inf 统一限制 (km/s)
        vinf=[0.1, 5.0],

        # 出发/到达超速损失均计入目标
        add_vinf_dep=True,
        add_vinf_arr=True,

        # 单目标: 最小化总 ΔV
        multi_objective=False,
    )

    prob = pg.problem(udp)
    print(prob)                             # 核对维度: 应为 18 (1+5+4+4+4)

    # ==================================================================
    # 3. 算法: 20 岛并行 + sade 3000 代
    #    18 维多局部极值问题, 必须大搜索量;
    #    核少可减 n=10, 但 pop_size 和 gen 别减
    # ==================================================================
    uda = pg.sade(gen=100)
    archi = pg.archipelago(
        n=10,
        algo=uda,
        prob=prob,
        pop_size=30,
        seed=42,
    )

    print('Running sade on 20 parallel islands, pop=40, gen=3000 ...')

    # ==================================================================
    # 4. 进化并等待完成
    # ==================================================================
    archi.evolve()
    archi.wait()

    # ==================================================================
    # 5. 提取结果
    #    champions_f = 总 ΔV, 单位 m/s
    # ==================================================================
    fs = archi.get_champions_f()
    xs = archi.get_champions_x()
    idx = fs.index(min(fs))

    print('\n各岛 ΔV (m/s):', sorted(round(f[0], 1) for f in fs))
    print('Best ΔV = %.1f m/s (= %.3f km/s)' % (min(fs)[0], min(fs)[0] / 1000))

    best = xs[idx]

    # ==================================================================
    # 6. 解码打印
    #    染色体 direct 编码 (18 维):
    #      x[0]: t0 (MJD2000) | x[1],x[2]: 出发 vinf 方向角
    #      x[3]: 出发 vinf 大小 (m/s!) | x[4]: 第1段 DSM 时刻比例
    #      x[5], x[9], x[13], x[17] : 各段飞行时间 (天)
    #      x[6..8], x[10..12], x[14..16]: 各段 [beta, rp/rV, DSM比例]
    # ==================================================================
    print('\n========== 最优解详情 ==========')
    udp.pretty(best)                        # pykep 自带人可读解码

    T = best[5::4]                          # 各段飞行时间 (天)
    print('\n发射 V_inf : %.2f km/s' % (best[3] / 1000))
    print('发射历元   :', epoch(best[0]))
    t_acc = best[0]
    for i, pl in enumerate(seq[1:]):
        t_acc += T[i]
        print('到达 %-8s: %s  (该段 %6.1f 天 ≈ %.2f 年)' % (
            pl.name, epoch(t_acc), T[i], T[i] / 365.25))
    print('总飞行时间 : %.1f 天 ≈ %.2f 年' % (sum(T), sum(T) / 365.25))

    # ==================================================================
    # 7. 绘制最优轨迹
    # ==================================================================
    try:
        import matplotlib
        matplotlib.use('TkAgg')             # 服务器无显示可改 'Agg'
        import matplotlib.pyplot as plt
        udp.plot(best)
        plt.title('EVVEJ (VEEGA) - total DV = %.2f km/s'
                  % (min(fs)[0] / 1000))
        plt.show()
    except Exception as e:
        print('绘图失败 (可忽略):', e)


if __name__ == '__main__':
    run()
